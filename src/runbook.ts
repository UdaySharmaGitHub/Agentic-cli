import fs from 'node:fs/promises';
import path from 'node:path';

export interface RunbookStep {
  stepNumber: number;
  task: string;
  reasoning: string;
  toolName: string;
  toolArgs: Record<string, unknown>;
  toolResult: string;
}

export interface RunbookSession {
  model: string;
  startedAt: Date;
  steps: RunbookStep[];
}

let session: RunbookSession | null = null;
let currentTask = '';

export function initSession(model: string): void {
  session = { model, startedAt: new Date(), steps: [] };
}

export function setCurrentTask(task: string): void {
  currentTask = task;
}

export function recordStep(entry: Omit<RunbookStep, 'stepNumber' | 'task'>): void {
  if (!session) return;
  session.steps.push({
    stepNumber: session.steps.length + 1,
    task: currentTask,
    ...entry,
  });
}

export function hasSteps(): boolean {
  return session !== null && session.steps.length > 0;
}

export function getSession(): RunbookSession | null {
  return session;
}

function buildFilename(ext: string): string {
  const date = new Date().toISOString().slice(0, 10);
  const firstTask = session?.steps[0]?.task ?? 'session';
  const slug = firstTask
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .slice(0, 40)
    .replace(/-+$/, '');
  return `agentic-runbook-${date}-${slug}.${ext}`;
}

function groupedTasks(steps: RunbookStep[]): { task: string; steps: RunbookStep[] }[] {
  const seen: string[] = [];
  for (const s of steps) {
    if (!seen.includes(s.task)) seen.push(s.task);
  }
  return seen.map(task => ({ task, steps: steps.filter(s => s.task === task) }));
}

// ── Markdown export ───────────────────────────────────────────────────────────

export async function exportMarkdown(outputDir = '.'): Promise<string> {
  if (!session) throw new Error('No active session.');
  const date = session.startedAt.toISOString().slice(0, 10);

  const lines: string[] = [
    `# Agent Runbook`,
    ``,
    `**Date:** ${date}`,
    `**Model:** ${session.model}`,
    `**Total Steps:** ${session.steps.length}`,
    ``,
    `---`,
    ``,
  ];

  for (const [i, group] of groupedTasks(session.steps).entries()) {
    lines.push(`## Task ${i + 1}: "${group.task}"`);
    lines.push(``);

    for (const step of group.steps) {
      lines.push(`### Step ${step.stepNumber} — \`${step.toolName}\``);
      lines.push(``);
      if (step.reasoning.trim()) {
        lines.push(`**Reasoning:** ${step.reasoning.trim()}`);
        lines.push(``);
      }
      lines.push(`**Arguments:**`);
      lines.push(`\`\`\`json`);
      lines.push(JSON.stringify(step.toolArgs, null, 2));
      lines.push(`\`\`\``);
      lines.push(``);
      const resultPreview = step.toolResult.length > 600
        ? step.toolResult.slice(0, 600) + '\n... (truncated)'
        : step.toolResult;
      lines.push(`**Result:**`);
      lines.push(`\`\`\``);
      lines.push(resultPreview);
      lines.push(`\`\`\``);
      lines.push(``);
    }

    lines.push(`---`);
    lines.push(``);
  }

  const filepath = path.resolve(outputDir, buildFilename('md'));
  await fs.writeFile(filepath, lines.join('\n'), 'utf-8');
  return filepath;
}

// ── Shell export ──────────────────────────────────────────────────────────────

export async function exportShell(outputDir = '.'): Promise<string> {
  if (!session) throw new Error('No active session.');
  const date = session.startedAt.toISOString().slice(0, 10);
  const shellSteps = session.steps.filter(s => s.toolName === 'run_command');

  const lines: string[] = [
    `#!/bin/bash`,
    `# Generated by agentic-cli`,
    `# Date:  ${date}`,
    `# Model: ${session.model}`,
    ``,
    `set -e`,
    ``,
  ];

  if (shellSteps.length === 0) {
    lines.push(`# No shell commands were executed in this session.`);
  } else {
    let lastTask = '';
    for (const step of shellSteps) {
      if (step.task !== lastTask) {
        lines.push(`# ── Task: ${step.task}`);
        lastTask = step.task;
      }
      const cmd = (step.toolArgs['command'] as string | undefined) ?? '';
      const firstLine = step.reasoning.trim().split('\n')[0];
      if (firstLine) lines.push(`# ${firstLine}`);
      lines.push(cmd);
      lines.push(``);
    }
  }

  const filepath = path.resolve(outputDir, buildFilename('sh'));
  await fs.writeFile(filepath, lines.join('\n'), 'utf-8');
  await fs.chmod(filepath, 0o755);
  return filepath;
}

// ── HTML export ───────────────────────────────────────────────────────────────

function escapeHtml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

interface BadgeStyle { bg: string; color: string; border: string }

function toolBadgeStyle(name: string): BadgeStyle {
  const map: Record<string, BadgeStyle> = {
    read_file:      { bg: '#1f3a5f22', color: '#58a6ff', border: '#2d5a9e44' },
    write_file:     { bg: '#1f3a5f22', color: '#58a6ff', border: '#2d5a9e44' },
    append_file:    { bg: '#1f3a5f22', color: '#58a6ff', border: '#2d5a9e44' },
    modify_file:    { bg: '#1f3a5f22', color: '#58a6ff', border: '#2d5a9e44' },
    run_command:    { bg: '#3d220022', color: '#f0883e', border: '#7d4e0044' },
    search_files:   { bg: '#2d1f5f22', color: '#bc8cff', border: '#5a3d9e44' },
    list_directory: { bg: '#1a3a2a22', color: '#56d364', border: '#2d6a4a44' },
    web_search:     { bg: '#1a3a2a22', color: '#3fb950', border: '#2d6a3a44' },
  };
  return map[name] ?? { bg: '#1f293722', color: '#8b949e', border: '#37415144' };
}

